"""Create mobile WebP cutouts without modifying the original photographs.

Run with a Python installation containing Pillow and WebP support.
"""
from concurrent.futures import ThreadPoolExecutor
from hashlib import sha256
import json
from pathlib import Path

from PIL import Image, ImageChops

ROOT = Path(__file__).resolve().parents[1]
ASSETS = ROOT / "theme-source" / "assets"
ENTRIES = json.loads((ROOT / "server" / "product-cutouts.json").read_text(encoding="utf-8"))
WIDTHS = (384, 768)
QUALITY = 92


def build(asset):
    original = ASSETS / asset
    original_bytes = original.read_bytes()
    with Image.open(original) as source:
        image = source.convert("RGBA")
    variants = []
    fallback = {"asset": asset, "width": image.width, "height": image.height, "bytes": len(original_bytes)}
    for width in sorted({min(width, image.width) for width in WIDTHS}):
        filename = f"{original.stem}-{width}.webp"
        output = ASSETS / filename
        if width == image.width and len(original_bytes) <= 80 * 1024:
            if output.exists():
                assert output.resolve().parent == ASSETS.resolve() and output != original
                output.unlink()
            variants.append(fallback)
            continue
        height = round(image.height * width / image.width)
        resized = image.resize((width, height), Image.Resampling.LANCZOS)
        resized.save(output, "WEBP", quality=QUALITY, method=6, exact=True)
        with Image.open(output) as decoded:
            assert decoded.size == resized.size, filename
            assert ImageChops.difference(
                decoded.convert("RGBA").getchannel("A"), resized.getchannel("A")
            ).getbbox() is None, f"Transparency changed: {filename}"
        if output.stat().st_size >= len(original_bytes):
            # Some older cutouts are already optimized; reuse them instead of a larger encoding.
            assert output.resolve().parent == ASSETS.resolve() and output != original
            output.unlink()
            variants.append(fallback)
        else:
            variants.append({"asset": filename, "width": width, "height": height, "bytes": output.stat().st_size})
    variants = sorted({item["asset"]: item for item in variants}.values(), key=lambda item: item["width"])
    assert original.read_bytes() == original_bytes, f"Original changed: {asset}"
    return asset, {"original_bytes": len(original_bytes), "original_sha256": sha256(original_bytes).hexdigest(), "variants": variants}


if __name__ == "__main__":
    assets = sorted({entry["asset"] for entry in ENTRIES})
    with ThreadPoolExecutor(max_workers=4) as pool:
        images = dict(pool.map(build, assets))
    report = {"format": "webp", "quality": QUALITY, "widths": list(WIDTHS), "images": images}
    (ROOT / "server" / "product-cutout-variants.json").write_text(
        json.dumps(report, indent=2) + "\n", encoding="utf-8"
    )
    # Keep Shopify and the local preview on exactly the same candidate list.
    source_cases = []
    preview_cases = []
    for asset, data in images.items():
        srcset = ", ".join("{{ '" + item["asset"] + "' | asset_url }} " + str(item["width"]) + "w" for item in data["variants"])
        source_cases.append("{%- when '" + asset + "' -%}\n<source type=\"image/webp\" media=\"(max-width: 767px)\" sizes=\"(max-width: 575px) calc(100vw - 40px), 50vw\" srcset=\"" + srcset + "\">")
        preview_cases.append("    when '" + asset + "'\n      echo '" + data["variants"][0]["asset"] + "'")
    snippets = ROOT / "theme-source" / "snippets"
    (snippets / "fem-cutout-sources.liquid").write_text(
        "{% doc %}\nGenerated by scripts/build-cutout-variants.py. Mobile sources retain the original img fallback.\n@param {string} photo_asset - Original WebP cutout.\n{% enddoc %}\n{%- case photo_asset -%}\n" + "\n".join(source_cases) + "\n{%- endcase -%}\n", encoding="utf-8"
    )
    (snippets / "fem-cutout-preview-asset.liquid").write_text(
        "{% doc %}\nGenerated by scripts/build-cutout-variants.py. Smallest useful source for fixed banners.\n@param {string} photo_asset - Original WebP cutout.\n{% enddoc %}\n{%- liquid\n  case photo_asset\n" + "\n".join(preview_cases) + "\n    else\n      echo photo_asset\n  endcase\n-%}\n", encoding="utf-8"
    )
    original_total = sum(item["original_bytes"] for item in images.values())
    largest_mobile = sum(item["variants"][-1]["bytes"] for item in images.values())
    generated_count = sum(variant["asset"] != asset for asset, item in images.items() for variant in item["variants"])
    print(f"Prepared {generated_count} smaller WebP files for {len(images)} cutouts, reusing originals when already lighter.")
    print(f"Original total: {original_total:,} bytes; largest mobile variants: {largest_mobile:,} bytes ({1 - largest_mobile / original_total:.1%} smaller).")
